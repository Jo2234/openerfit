import { readFile } from 'node:fs/promises';
import { describe, expect, it } from 'vitest';
import { z } from 'zod';
import { extractParamSchema, serializeParamSchema } from '../../scripts/extract-param-schema';
import { briefRequestSchema, claimSelectionSchema } from '../../src/shared/schemas';
import scenarios from '../../fixtures/scenarios.json';
describe('S0 frozen snapshot and v1.1 contracts', () => {
  it('Q4: generated bytes, source hashes and authoritative guide tiers are stable', async () => {
    const generated = await extractParamSchema();
    expect(serializeParamSchema(generated)).toBe(await readFile('src/qloo/param-schema.generated.json', 'utf8'));
    expect(generated.insights['urn:entity:artist']['filter.results.entities'].tier).toBe('guide');
    expect(generated.insights['urn:entity:artist']['signal.location'].tier).toBe('reference_only');
    expect(generated.insights['urn:entity:place']['filter.location'].tier).toBe('guide');
    expect(generated.insights['urn:entity:place']['filter.location.query'].tier).toBe('reference_only');
  });
  it('accepts the eight-row preset and seven confirmed IDs', () => {
    expect(briefRequestSchema.safeParse(scenarios[0].request).success).toBe(true);
    expect(scenarios[0].confirmedRosterIds).toHaveLength(7);
  });
  it('writer selection exports catalogue enum and rejects forged IDs, duplicates, excess selections and prose', () => {
    const ids = Array.from({length: 13}, (_, i) => `fact-${i}`);
    const schema = claimSelectionSchema(ids);
    const exported = z.toJSONSchema(schema);
    expect(exported.properties?.claimIds).toMatchObject({type: 'array', maxItems: 12, items: {type: 'string', enum: ids}});
    expect(exported.additionalProperties).toBe(false);
    expect(schema.safeParse({claimIds: ids.slice(0, 12)}).success).toBe(true);
    expect(schema.safeParse({claimIds: []}).success).toBe(true);
    for (const value of [{claimIds:['forged']}, {claimIds:['fact-0','fact-0']}, {claimIds:ids}, {claimIds:[],text:'Arbitrary assertion'}]) expect(schema.safeParse(value).success).toBe(false);
    const pair = z.toJSONSchema(claimSelectionSchema(['fact-a','fact-b']));
    expect(pair.properties?.claimIds).toMatchObject({items: {enum: ['fact-a','fact-b']}});
  });
  it('empty catalogue exports an empty-list-only contract and accepts no IDs or prose', () => {
    const schema = claimSelectionSchema([]);
    const exported = z.toJSONSchema(schema);
    expect(exported.properties?.claimIds).toMatchObject({type: 'array', minItems: 0, maxItems: 0});
    expect(exported.additionalProperties).toBe(false);
    expect(schema.safeParse({claimIds: []}).success).toBe(true);
    for (const value of [{claimIds:['forged']}, {claimIds:[],text:'Arbitrary assertion'}, {}, {claimIds:null}]) expect(schema.safeParse(value).success).toBe(false);
  });
});
